import { chromium } from 'playwright-core';
import assert from 'node:assert/strict';
import fs from 'node:fs';
const chrome=process.env.CHROME_PATH||'/usr/bin/google-chrome';
const browser=await chromium.launch({headless:true,executablePath:chrome,args:['--no-sandbox','--disable-dev-shm-usage']});
const errors=[];
try {
 const page=await browser.newPage({viewport:{width:1440,height:900},deviceScaleFactor:1});
 page.on('pageerror',err=>errors.push(err.message));
 await page.goto('http://127.0.0.1:4173/',{waitUntil:'domcontentloaded'});
 await page.locator('#hero-play').click();
 await page.locator('#player-name').fill('Tester');
 await page.locator('#practice-btn').click();
 await page.locator('#my-card .card-name').waitFor({timeout:10000});
 assert.match(await page.locator('#you-count').textContent(),/^25$/);
 assert.match(await page.locator('#enemy-count').textContent(),/^25$/);
 const statButtons=page.locator('.stat-button');assert.equal(await statButtons.count(),8);
 const enabled=statButtons.filter({hasText:/RANK|HEIGHT|WEIGHT|ATTACK|DEFENSE|SPEED|ENG|HP/});
 assert.equal(await enabled.count(),8);
 await page.screenshot({path:'/tmp/deckverse-desktop.png',fullPage:true});
 const chose=await page.locator('.stat-button:not([disabled])').count();
 if(chose)await page.locator('.stat-button:not([disabled])').first().click();
 else assert.ok(['WAITING ON YOUR RIVAL','BOTH CARDS REVEALED'].includes(await page.locator('#battle-status').textContent()),'Bot can be waiting or revealing its first move');
 await page.locator('#result.compact').waitFor({timeout:5500});
 assert.ok(await page.locator('#my-card .card-name').isVisible(),'Our played card is visible during result');
 assert.ok(await page.locator('#their-card .card-name').isVisible(),'Opponent played card is visible during result');
 assert.ok(await page.locator('#result .reveal-summary').isVisible(),'Results do not replace the cards');
 await page.waitForTimeout(2600);
 assert.ok(Number(await page.locator('#round-number').textContent())>=2,'Practice turn must advance');
 await page.setViewportSize({width:390,height:844});
 await page.goto('http://127.0.0.1:4173/',{waitUntil:'domcontentloaded'});
 assert.equal(await page.locator('.theme-card').count(),3);
 const overflow=await page.evaluate(()=>document.documentElement.scrollWidth-window.innerWidth);
 if(overflow>2)console.log('OVERFLOW ELEMENTS',JSON.stringify(await page.evaluate(()=>[...document.querySelectorAll('body *')].map(e=>{const r=e.getBoundingClientRect();return {tag:e.tagName,cls:typeof e.className==='string'?e.className:'',right:Math.round(r.right),left:Math.round(r.left),w:Math.round(r.width),scroll:e.scrollWidth}}).filter(e=>e.right>window.innerWidth+4||e.left<-4).sort((a,b)=>b.right-a.right).slice(0,18))));
 assert.ok(overflow<=2,'Mobile viewport should not overflow, overflow='+overflow);
 await page.screenshot({path:'/tmp/deckverse-mobile.png',fullPage:true});
 await page.locator('#pokemon-tile').click();
 assert.ok(await page.locator('#setup').isVisible());
 await page.locator('#practice-btn').click();
 await page.locator('#my-card .card-name').waitFor();
 const battleOverflow=await page.evaluate(()=>document.documentElement.scrollWidth-window.innerWidth);
 assert.ok(battleOverflow<=2,'Mobile arena overflow: '+battleOverflow);
 await page.screenshot({path:'/tmp/deckverse-battle-mobile.png',fullPage:true});
 assert.deepEqual(errors,[],'Unhandled browser errors');
 console.log('PASS: Desktop landing, theme selection, 50-card practice, stat selection, responsive mobile layout and gameplay');
} finally {await browser.close()}
